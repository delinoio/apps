// Generate native and frontend registries from the same reviewed source files.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../..", import.meta.url));
const directory = path.join(root, "apps/fixkey/src/translations");
const codes = readdirSync(directory)
  .filter((file) => file.endsWith(".json"))
  .map((file) => file.slice(0, -5))
  .sort();
const en = JSON.parse(readFileSync(path.join(directory, "en.json"), "utf8"));
function shape(source, value, location) {
  if (typeof source === "string") {
    if (typeof value !== "string" || !value.trim())
      throw new Error(`translation-string-missing: ${location}`);
  } else if (Array.isArray(source)) {
    if (!Array.isArray(value) || value.length !== source.length)
      throw new Error(`translation-array-mismatch: ${location}`);
    source.forEach((entry, index) =>
      shape(entry, value[index], `${location}.${index}`),
    );
  } else {
    if (!value || Object.keys(source).join() !== Object.keys(value).join())
      throw new Error(`translation-keys-mismatch: ${location}`);
    for (const key of Object.keys(source))
      shape(source[key], value[key], `${location}.${key}`);
  }
}
for (const code of codes)
  shape(
    en,
    JSON.parse(readFileSync(path.join(directory, `${code}.json`), "utf8")),
    code,
  );
const variant = (code) =>
  code
    .split("-")
    .map((part) => part[0].toUpperCase() + part.slice(1).toLowerCase())
    .join("");
let rust = `//! Generated by scripts/fixkey/generate-locales.mjs. Do not edit by hand.\n\nuse serde::{Deserialize, Serialize};\n\n/// A complete bundled UI translation, or the operating-system preference.\n#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]\npub enum UiLanguage {\n    /// Follow the operating-system locale.\n    #[default]\n    #[serde(rename = "system")]\n    System,\n`;
rust += codes
  .map(
    (code) =>
      `    /// ${code}.\n    #[serde(rename = "${code}")]\n    ${variant(code)},\n`,
  )
  .join("");
rust += `}\n\nimpl UiLanguage {\n    /// Resolves exact locale, language/script prefix, base language, then English.\n    #[must_use]\n    pub fn resolve(self, os_locale: &str) -> &'static str {\n        match self {\n            Self::System => Self::from_locale(os_locale).resolve("en"),\n`;
rust += codes
  .map((code) => `            Self::${variant(code)} => "${code}",\n`)
  .join("");
rust += `        }\n    }\n\n    #[must_use]\n    pub fn from_locale(locale: &str) -> Self {\n        let normalized = locale.split(['.', '@']).next().unwrap_or("en").replace('_', "-").to_ascii_lowercase();\n        let mut candidate = normalized.as_str();\n        loop {\n            match candidate {\n`;
rust += codes
  .map(
    (code) =>
      `                "${code.toLowerCase()}" => return Self::${variant(code)},\n`,
  )
  .join("");
rust += `                _ => {}\n            }\n            let Some((prefix, _)) = candidate.rsplit_once('-') else { return Self::En };\n            candidate = prefix;\n        }\n    }\n}\n\nconst SOURCES: &[(&str, &str)] = &[\n`;
rust += codes
  .map(
    (code) =>
      `    ("${code}", include_str!("../../src/translations/${code}.json")),\n`,
  )
  .join("");
rust += `];\n\n/// Uses the same bundled messages as settings, permission dialogs and help.\n///\n/// # Panics\n///\n/// Panics if a compiled-in translation is not valid JSON.\n#[must_use]\npub fn text(locale: &str, key: &str) -> &'static str {\n    static MESSAGES: std::sync::OnceLock<std::collections::BTreeMap<&'static str, serde_json::Value>> = std::sync::OnceLock::new();\n    let messages = MESSAGES.get_or_init(|| SOURCES.iter().map(|(locale, source)| (*locale, serde_json::from_str(source).expect("valid bundled translation"))).collect());\n    let locale = UiLanguage::from_locale(locale).resolve("en");\n    messages.get(locale).and_then(|value| value.get(key)).and_then(serde_json::Value::as_str).unwrap_or("")\n}\n`;
writeFileSync(
  path.join(root, "apps/fixkey/src-tauri/src/localization.rs"),
  rust,
);
let ts = "// Generated by scripts/fixkey/generate-locales.mjs.\n";
ts += codes
  .map(
    (code) => `import ${variant(code)} from "./translations/${code}.json";\n`,
  )
  .join("");
ts += `\nexport const messages = {\n${codes.map((code) => `  "${code}": ${variant(code)},\n`).join("")} } as const;\nexport type UiLocale = keyof typeof messages;\n\nexport function resolveLocale(locale: string): UiLocale {\n  let candidate = locale.split(/[.@]/)[0].replaceAll("_", "-").toLowerCase();\n  for (;;) {\n    const match = Object.keys(messages).find((code) => code.toLowerCase() === candidate);\n    if (match) return match as UiLocale;\n    const end = candidate.lastIndexOf("-");\n    if (end < 0) return "en";\n    candidate = candidate.slice(0, end);\n  }\n}\n\nexport const isRtl = (locale: string) => ["he", "fa"].includes(resolveLocale(locale));\n`;
writeFileSync(path.join(root, "apps/fixkey/src/locale.ts"), ts);
const catalog = JSON.parse(
  readFileSync(
    path.join(root, "crates/fixkey-core/assets/languages/catalog.json"),
    "utf8",
  ),
);
writeFileSync(
  path.join(root, "apps/fixkey/src/languages.json"),
  JSON.stringify(catalog.languages, null, 2) + "\n",
);
console.log(
  JSON.stringify({
    component: "fixkey.locales",
    locales: codes.length,
    result: "generated",
  }),
);
